export const t = (text: string, language: string): string => {
  if (!text || !language || language.toLowerCase() === 'english') return text;
  const langKey = language.split(' ')[0];
  const dict = UI_TRANSLATIONS[langKey];
  return (dict && dict[text]) ? dict[text] : text;
};

